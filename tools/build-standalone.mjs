// Build the single-file English edition: one HTML file with all code, CSS and question banks inside.
// Images load from the public GitHub repo through a CDN (see src/standalone/assetInit.ts).
//
//   node tools/build-standalone.mjs            -> dist-standalone/live-class-en.html (+ .js, index.html), images from the CDN
//   node tools/build-standalone.mjs --offline  -> dist-standalone/live-class-en-offline.html, every image inside (about 2 MB)
//
// No npm install needed when run with the tools in /opt/npm-tools (esbuild, tailwindcss, react).
// With a normal checkout: `npm i -D esbuild` and point NODE_MODULES below at ./node_modules.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const NM = [path.join(root, 'node_modules'), '/opt/npm-tools/node_modules'].find((d) => fs.existsSync(path.join(d, 'esbuild')));
if (!NM) throw new Error('esbuild not found: run npm i -D esbuild');
const req = createRequire(path.join(NM, 'x.js'));
const esbuild = req('esbuild');
const { compile } = await import(path.join(NM, 'tailwindcss/dist/lib.mjs'));
const out = path.join(root, 'dist-standalone');
fs.mkdirSync(out, { recursive: true });

// ---------- 1. CSS: Tailwind v4 (only the classes the code uses) + game CSS ----------
const srcFiles = [];
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (/\.(tsx?|css)$/.test(f) && !f.includes('.check.') && !f.startsWith('generated-')) srcFiles.push(p);
  }
})(path.join(root, 'src'));
const candidates = new Set();
for (const f of srcFiles) for (const t of fs.readFileSync(f, 'utf8').split(/[\s'"`{}]+/)) if (t && t.length < 120) candidates.add(t.replace(/^[(,]+|[),;]+$/g, ''));

const twDir = path.join(NM, 'tailwindcss');
const readCss = (f) => fs.readFileSync(f, 'utf8');
const gameCss = readCss(path.join(root, 'src/index.css')).replace(/@import\s+['"]tailwindcss['"];?/, '').replace(/\.stage-bg\s*\{[^}]*\}/, '');
const stageCss = readCss(path.join(root, 'src/game/stage.css'));
const input = `@import 'tailwindcss';\n${gameCss}\n${stageCss}\n
/* inside the shadow root the app starts from a clean slate, whatever the blog theme does:
   blog CSS can still style the host <div> itself (and its inherited font, size, line-height...), so the root resets all of it */
:host { display: block !important; width: 100%; }
.lc-root { all: initial; display: block; width: 100%; color: #e2e8f0; font-family: 'Be Vietnam Pro', system-ui, sans-serif; font-size: 16px; line-height: 1.5; text-align: left; -webkit-text-size-adjust: 100%; tab-size: 4; }
/* phones: iOS zooms into any text field under 16px when it gets focus; keep fields at 16px so the page never jumps */
@media (max-width: 767px) { .lc-root input:not([type=range]), .lc-root select, .lc-root textarea { font-size: 16px !important; } }
/* the quick-reply row scrolls sideways on small screens: hide its scrollbar */
.lc-quick { scrollbar-width: none; -webkit-overflow-scrolling: touch; }
.lc-quick::-webkit-scrollbar { display: none; }
.lc-root img { max-width: none; }
.lc-full .lc-root, .lc-full { width: 100vw; height: 100vh; }
/* iPhone: 100vh reaches under Safari's toolbar and would hide the answer box; dvh is the visible height */
@supports (height: 100dvh) { .lc-full .lc-root, .lc-full { height: 100dvh; } }
`;
const compiler = await compile(input, {
  base: root,
  loadStylesheet: async (id, base) => {
    const map = { tailwindcss: 'index.css', 'tailwindcss/index.css': 'index.css', 'tailwindcss/theme': 'theme.css', 'tailwindcss/theme.css': 'theme.css', 'tailwindcss/preflight': 'preflight.css', 'tailwindcss/preflight.css': 'preflight.css', 'tailwindcss/utilities': 'utilities.css', 'tailwindcss/utilities.css': 'utilities.css' };
    const file = map[id] ? path.join(twDir, map[id]) : path.resolve(base, id);
    return { path: file, base: path.dirname(file), content: readCss(file) };
  },
});
let css = compiler.build([...candidates]);
// .stage-bg and other url('/assets/...') are set inline by the app (CDN images)
css = css.replace(/url\(['"]?\/assets\/[^)]*\)/g, 'none');
// @property rules must live in the page <head> (ignored inside a shadow root)
const props = [];
css = css.replace(/@property\s+[^{]+\{[^}]*\}/g, (m) => (props.push(m), ''));
const min = async (c) => (await esbuild.transform(c, { loader: 'css', minify: true, target: ['chrome100', 'safari15', 'firefox100'] })).code;
const CSS = await min(css);
const GLOBAL_CSS = await min(props.join('\n'));
fs.writeFileSync(path.join(root, 'src/standalone/generated-css.ts'), `// generated by tools/build-standalone.mjs\nexport const CSS = ${JSON.stringify(CSS)};\nexport const GLOBAL_CSS = ${JSON.stringify(GLOBAL_CSS)};\n`);
console.log(`css ${(CSS.length / 1024).toFixed(0)} KB, @property ${props.length}`);

// ---------- 2. offline build: embed every image (resized + recompressed) as data URLs ----------
const OFFLINE = process.argv.includes('--offline');
let inlineFile = path.join(root, 'src/standalone/inline-assets.ts');
if (OFFLINE) {
  const sharp = req('sharp');
  const map = {};
  let bytes = 0;
  const pub = path.join(root, 'public');
  const files = [];
  (function walk(d) {
    for (const f of fs.readdirSync(d)) {
      const p = path.join(d, f);
      if (fs.statSync(p).isDirectory()) walk(p);
      else if (p.endsWith('.webp') && !p.includes(`${path.sep}co-giao${path.sep}`)) files.push(p);
    }
  })(path.join(pub, 'assets'));
  for (const f of files) {
    const rel = '/' + path.relative(pub, f).split(path.sep).join('/');
    // students are drawn small on the stage, teachers medium, the background full size
    const scale = rel.includes('/bg/') ? 1 : /\/nv\/(nam|nu)\//.test(rel) ? 0.5 : 0.72;
    const img = sharp(f);
    const meta = await img.metadata();
    const buf = await img
      .resize(Math.round(meta.width * scale))
      .webp({ quality: rel.includes('/bg/') ? 72 : 78, effort: 4 })
      .toBuffer();
    bytes += buf.length;
    map[rel] = `data:image/webp;base64,${buf.toString('base64')}`;
  }
  inlineFile = path.join(root, 'src/standalone/generated-inline-assets.ts');
  fs.writeFileSync(inlineFile, `// generated by tools/build-standalone.mjs --offline\nexport const INLINE_ASSETS: Record<string, string> = ${JSON.stringify(map)};\n`);
  console.log(`offline: ${files.length} images embedded, ${(bytes / 1024).toFixed(0)} KB`);
}

// ---------- 3. JS bundle ----------
const glob = {
  name: 'vite-glob-and-css',
  setup(b) {
    // import.meta.glob('./dir/*.txt', { query: '?raw', eager: true }) -> object literal with the file contents
    b.onLoad({ filter: /src[\\/]game[\\/]bank\.ts$/ }, async (a) => {
      let src = fs.readFileSync(a.path, 'utf8');
      src = src.replace(/import\.meta\.glob\(\s*'\.\/([^/']+)\/\*\.txt'[^)]*\)/g, (_, dir) => {
        const d = path.join(path.dirname(a.path), dir);
        const obj = Object.fromEntries(
          fs.readdirSync(d).filter((f) => f.endsWith('.txt')).sort().map((f) => [`./${dir}/${f}`, fs.readFileSync(path.join(d, f), 'utf8')]),
        );
        return JSON.stringify(obj);
      });
      return { contents: src, loader: 'ts' };
    });
    // offline build: swap the empty image map for the generated one
    b.onResolve({ filter: /\/inline-assets$/ }, () => ({ path: inlineFile }));
    // CSS is compiled above and injected into the shadow root
    b.onResolve({ filter: /\.css$/ }, (a) => ({ path: a.path, namespace: 'nocss' }));
    b.onLoad({ filter: /.*/, namespace: 'nocss' }, () => ({ contents: '', loader: 'js' }));
  },
};
const res = await esbuild.build({
  entryPoints: [path.join(root, 'src/standalone/main.tsx')],
  bundle: true,
  write: false,
  format: 'iife',
  minify: true,
  charset: 'ascii', // Blogger turns non-ASCII characters into &#...; entities: keep the script pure ASCII
  legalComments: 'none',
  target: ['chrome100', 'safari15', 'firefox100'],
  alias: { 'motion/react': path.join(root, 'src/standalone/motion.tsx') },
  nodePaths: [NM],
  define: { 'process.env.NODE_ENV': '"production"', __STANDALONE__: 'true' },
  jsx: 'automatic',
  plugins: [glob],
  metafile: true,
  logLevel: 'warning',
});
let js = res.outputFiles[0].text;
// never let the script text close its own <script> tag or open an HTML comment
js = js.replace(/<\/(script)/gi, '<\\/$1').replace(/<!--/g, '<\\!--');
// esbuild escapes strings, but leaves a few characters inside regex literals: escape whatever is left
// (\\uXXXX is valid in strings, templates and regexes alike; astral characters become surrogate pairs)
js = js.replace(/[^\x00-\x7e]/gu, (ch) => Array.from(ch.split(''), (u) => '\\u' + u.charCodeAt(0).toString(16).padStart(4, '0')).join(''));
const nonAscii = [...js].filter((c) => c.charCodeAt(0) > 126).length;
if (nonAscii) throw new Error(`bundle still has ${nonAscii} non-ASCII characters`);
const NAME = OFFLINE ? 'live-class-en-offline' : 'live-class-en';
fs.writeFileSync(path.join(out, `${NAME}.js`), js);

// ---------- 4. HTML ----------
const html = `<!-- LIVE-CLASS English edition: single-file build. Paste this whole block into a Blogger post (HTML view) or any page. -->
<div id="live-class-en" style="width:100%;max-width:1100px;margin:0 auto;min-height:200px"></div>
<script>
${js}
</script>
`;
fs.writeFileSync(path.join(out, `${NAME}.html`), html);
const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
<title>LIVE-CLASS - Interactive Classroom Game Show (English)</title>
<style>html,body{margin:0;background:#0b1020;}body{padding:12px 8px;}</style>
</head>
<body>
${html}</body>
</html>
`;
fs.writeFileSync(path.join(out, OFFLINE ? 'index-offline.html' : 'index.html'), page);
console.log(`js ${(js.length / 1024).toFixed(0)} KB, html ${(html.length / 1024).toFixed(0)} KB`);
const top = Object.entries(res.metafile.inputs).sort((a, b) => b[1].bytes - a[1].bytes).slice(0, 8);
for (const [k, v] of top) console.log(`  ${(v.bytes / 1024).toFixed(0).padStart(5)} KB  ${k.replace(/.*node_modules\//, '')}`);
